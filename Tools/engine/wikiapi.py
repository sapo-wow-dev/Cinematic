"""Imports the Warcraft Wiki's API tags into the engine rules. From the repo root:

    python -I Tools/engine/wikiapi.py            (downloads the page)
    python -I Tools/engine/wikiapi.py page.txt   (a saved copy of ?action=raw)

The wiki's World of Warcraft API page tags functions with what the game
restricts: protected, nocombat, hwevent, noinstance, noscript, grouponly,
deprecated. This script:

1. writes Tools/engine/wiki-api-tags.lua: every tagged function and its tags
   (names and tags only; the wiki's text is CC BY-SA, so none of it is kept);
2. scans Cinematic's own code (not Tools/) for calls to tagged functions;
3. writes Tools/engine/rules/wiki-tags.lua: one "inferred" rule per tagged call
   the code makes that no hand-written rule names in its api list;
4. prints the hand-written rules that name a tagged call, to compare by eye.

The wiki is written for retail, so the generated rules say retail only; a test
in game on another client becomes a hand-written rule (and drops the generated
one on the next run). Needs lupa (pip install lupa), like Tools/offline/run.py.
"""
import datetime
import os
import re
import sys
import urllib.request

import lupa.lua51 as lua51

PAGE = "https://warcraft.wiki.gg/wiki/World_of_Warcraft_API"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TAGS_FILE = os.path.join(ROOT, "Tools", "engine", "wiki-api-tags.lua")
RULES_FILE = os.path.join(ROOT, "Tools", "engine", "rules", "wiki-tags.lua")
GENERATED_AREA = "wiki-tags"
SKIP_DIRS = {"Tools", "Release", "docs", ".git", ".claude", "Libs"}
KEEP_TAGS = ["protected", "nocombat", "hwevent", "noinstance", "noscript", "grouponly", "deprecated"]

# Our own words per tag: (when, rule text).
TAG_RULE = {
    "protected": ("always", "{f} is protected: only Blizzard's secure code may call it. From an addon it is blocked "
                  "(ADDON_ACTION_BLOCKED / \"Interface action failed\")."),
    "nocombat": ("in combat", "{f} can't be called in combat (InCombatLockdown true); out of combat it works."),
    "hwevent": ("always", "{f} needs a hardware event: it only works inside a real key press or mouse click, "
                "not from an OnUpdate, a timer or an event."),
    "noinstance": ("in instances", "{f} returns nothing useful inside instances (dungeons, raids, battlegrounds)."),
    "noscript": ("always", "{f} is blocked from /run and /script macros (addon code is not affected by this tag)."),
    "grouponly": ("when not in a group", "{f} only works while in a group."),
    "deprecated": ("always", "{f} is deprecated: it may be gone in a later patch; use its replacement."),
}

LINE = re.compile(r"^:\s*\[\[API:([^|\]]+)\|[^\]]*\]\].*?\{\{apitag\|([^}]*)\}\}")
NOTE = re.compile(r"up to date as of ([^}]*?)\}\}")


def fetch(path):
    if path:
        with open(path, encoding="utf-8") as f:
            return f.read()
    req = urllib.request.Request(PAGE + "?action=raw", headers={"User-Agent": "Mozilla/5.0 (engine rules import)"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def parse(text):
    tags = {}
    for line in text.splitlines():
        m = LINE.match(line)
        if not m:
            continue
        name = m.group(1).strip().replace(" ", "_")
        got = [t.strip() for t in m.group(2).split(",") if t.strip() in KEEP_TAGS]
        if got:
            tags[name] = sorted(set(tags.get(name, []) + got), key=KEEP_TAGS.index)
    note = NOTE.search(text)
    patch = re.sub(r"\[\[[^|\]]*\|([^\]]*)\]\]", r"\1", note.group(1)).strip() if note else "unknown patch"
    return tags, patch


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_tags(tags, patch, today):
    out = [
        "-- Generated by Tools/engine/wikiapi.py: do not edit by hand, run the script again.",
        "-- Function names and their restriction tags from " + PAGE,
        "-- (" + patch + ", fetched " + today + "). Retail tags; Forever and Classic Era can differ.",
        "-- Facts only: no wiki text (CC BY-SA) is copied.",
        "return {",
        "  page = " + lua_str(PAGE) + ",",
        "  patch = " + lua_str(patch) + ",",
        "  fetched = " + lua_str(today) + ",",
        "  tags = {",
    ]
    for name in sorted(tags):
        out.append("    [" + lua_str(name) + "] = { " + ", ".join(lua_str(t) for t in tags[name]) + " },")
    out += ["  },", "}", ""]
    with open(TAGS_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


def load_rules():
    """The hand-written rules (every area but the generated one), via the same loader the checks use."""
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    os.chdir(ROOT)
    rules, areas = lua.execute('return dofile("Tools/engine/rules.lua")')
    out = []
    for i in range(1, len(rules) + 1):
        r = rules[i]
        if r.file == GENERATED_AREA:
            continue
        api = [r.api[j] for j in range(1, len(r.api) + 1)] if r.api else []
        out.append({"id": r.id, "file": r.file, "api": api, "status": r.status})
    return out


def code_files():
    for base, dirs, files in os.walk(ROOT):
        rel = os.path.relpath(base, ROOT)
        if rel.split(os.sep)[0] in SKIP_DIRS:
            dirs[:] = []
            continue
        for name in files:
            if name.endswith(".lua"):
                yield os.path.join(base, name)


def find_calls(tags):
    """{name: sorted list of 'file:line'} for each tagged function the code calls."""
    patterns = {n: re.compile(r"(?<![\w.:])" + re.escape(n) + r"\s*\(") for n in tags}
    # Cheap prefilter: the bare last part of the name must appear on the line.
    last = {n: n.split(".")[-1] for n in tags}
    found = {}
    for path in code_files():
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        with open(path, encoding="utf-8", errors="replace") as f:
            for no, line in enumerate(f, 1):
                code = line.split("--", 1)[0]
                if "(" not in code:
                    continue
                for n, pat in patterns.items():
                    if last[n] in code and pat.search(code):
                        found.setdefault(n, []).append(rel + ":" + str(no))
    return found


def rule_id(name):
    return "retail.wiki." + re.sub(r"[^\w.-]", "-", name.replace(":", ".")).lower()


def write_rules(tags, patch, calls, covered):
    out = [
        "-- Generated by Tools/engine/wikiapi.py: do not edit by hand, run the script again.",
        "-- One inferred rule per wiki-tagged call Cinematic's code makes that no hand-written rule covers.",
        "-- When a test in game shows one, write it by hand in its area file; the next run drops it here.",
        "return {",
    ]
    for name in sorted(calls):
        if name in covered:
            continue
        for tag in tags[name]:
            when, text = TAG_RULE[tag]
            where = calls[name]
            seen = ", ".join(where[:3]) + (" (+%d more)" % (len(where) - 3) if len(where) > 3 else "")
            out += [
                "  {",
                "    id = " + lua_str(rule_id(name) + "." + tag) + ",",
                '    area = "wiki",',
                '    clients = { "retail" },',
                "    api = { " + lua_str(name) + " },",
                "    when = " + lua_str(when) + ",",
                "    rule = " + lua_str(text.format(f=name + "()") + " Called in: " + seen + ".") + ",",
                '    status = "inferred",',
                "    proof = " + lua_str("wiki tag #" + tag + " (" + patch + ")") + ",",
                "    source = " + lua_str("wiki: " + PAGE) + ",",
                "  },",
            ]
    out += ["}", ""]
    with open(RULES_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


def selftest():
    """python -I Tools/engine/wikiapi.py --selftest: the parser on made-up page lines."""
    text = "\n".join([
        "{{i-note|This page is up to date as of PTR [[Patch_9.9/API_changes|Patch 9.9]] (1) Jan 1 2030}}",
        ": [[API:Quit|Quit]]() {{apitag|protected}}",
        ": [[API:C_X.Do|C_X.Do]](<span class=\"apiarg\">a</span>) : <span class=\"apiret\">b</span> {{apitag|hwevent,noscript}}",
        ": [[API:UIParentLoadAddOn|UIParentLoadAddOn]](name) {{apitag|framexml}}",
        ": [[API:GetTime|GetTime]]() : <span class=\"apiret\">seconds</span>",
    ])
    tags, patch = parse(text)
    problems = []
    if tags != {"Quit": ["protected"], "C_X.Do": ["hwevent", "noscript"]}:
        problems.append("tags: %r" % tags)
    if patch != "PTR Patch 9.9 (1) Jan 1 2030":
        problems.append("patch: %r" % patch)
    if rule_id("Frame:SetPoint") != "retail.wiki.frame.setpoint" or rule_id("C_UI.Reload") != "retail.wiki.c_ui.reload":
        problems.append("rule_id: %r" % rule_id("Frame:SetPoint"))
    pat = re.compile(r"(?<![\w.:])" + re.escape("Quit") + r"\s*\(")
    if not pat.search("Quit()") or pat.search("ForceQuit()") or pat.search("x:Quit()"):
        problems.append("call match")
    for p in problems:
        print("FAIL " + p)
    print("OK" if not problems else "FAILED")
    sys.exit(1 if problems else 0)


def main():
    if sys.argv[1:] == ["--selftest"]:
        return selftest()
    text = fetch(sys.argv[1] if len(sys.argv) > 1 else None)
    tags, patch = parse(text)
    if len(tags) < 50:
        sys.exit("only %d tagged functions found: the page's layout changed? nothing written" % len(tags))
    today = datetime.date.today().isoformat()
    write_tags(tags, patch, today)

    rules = load_rules()
    named = {}
    for r in rules:
        for a in r["api"]:
            a = a.rstrip("()")
            if a in tags:
                named.setdefault(a, []).append(r)
    calls = find_calls(tags)
    write_rules(tags, patch, calls, named)

    print("%d tagged functions (%s) -> %s" % (len(tags), patch, os.path.relpath(TAGS_FILE, ROOT)))
    print("%d tagged calls in Cinematic's code, %d named by hand-written rules"
          % (len(calls), sum(1 for n in calls if n in named)))
    gaps = sorted(n for n in calls if n not in named)
    print("%d calls with no hand-written rule -> %s" % (len(gaps), os.path.relpath(RULES_FILE, ROOT)))
    for n in gaps:
        print("  NEW   %-40s #%s  (%s)" % (n, ",#".join(tags[n]), calls[n][0]))
    print("Hand-written rules that name a tagged call (compare their text with the tag):")
    for n in sorted(named):
        for r in named[n]:
            print("  CHECK %-40s #%-12s %s [%s]" % (n, ",#".join(tags[n]), r["id"], r["status"]))


if __name__ == "__main__":
    main()
